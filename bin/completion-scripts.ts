import { CliUsageError } from "./scan-actions.js";

export const COMPLETION_SHELLS = ["bash", "zsh", "fish"] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

const TOP_LEVEL_COMMANDS =
  "init doctor scan baseline compare completion" as const;

const SCAN_FLAGS =
  "--since --format --output --exclude --include --config --top --baseline --concurrency --sequential --no-overlap --include-tests --quiet --verbose --no-progress --dry-run --only --no-triage-hints --no-color --explain --strict --warnings" as const;

const BASH_COMPLETION_SCRIPT = `# hotspot-scanner bash completion
# Generated by: hotspot-scanner completion bash

_hotspot_scanner() {
  local cur
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"

  if [[ \${COMP_CWORD} -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "${TOP_LEVEL_COMMANDS}" -- "\${cur}") )
    return 0
  fi

  case "\${COMP_WORDS[1]}" in
    baseline)
      if [[ \${COMP_CWORD} -eq 2 ]]; then
        COMPREPLY=( $(compgen -W "save" -- "\${cur}") )
      else
        COMPREPLY=( $(compgen -W "--output --since --exclude --include --config --top --concurrency --sequential --no-overlap --include-tests --warnings --help" -- "\${cur}") )
      fi
      ;;
    scan|compare)
      COMPREPLY=( $(compgen -W "${SCAN_FLAGS} --help" -- "\${cur}") )
      ;;
    completion)
      COMPREPLY=( $(compgen -W "bash zsh fish" -- "\${cur}") )
      ;;
    *)
      COMPREPLY=( $(compgen -W "--help" -- "\${cur}") )
      ;;
  esac
}

complete -F _hotspot_scanner hotspot-scanner
`;

const ZSH_COMPLETION_SCRIPT = `#compdef hotspot-scanner

_hotspot_scanner() {
  local context state line
  typeset -A opt_args

  _arguments -C \\
    '1: :->command' \\
    '*:: :->args'

  case $state in
    command)
      local -a commands
      commands=(
        'init:Write exemplar .hotspot-scanner.json'
        'doctor:Check Node, git, repository, and config readiness'
        'scan:Run hotspot analysis'
        'baseline:Baseline file workflows'
        'compare:Compare current scan against a baseline JSON file'
        'completion:Print shell completion script'
      )
      _describe 'command' commands
      ;;
    args)
      case $words[1] in
        scan)
          _arguments \\
            '--since[Git history window]' \\
            '--format[Output format]' \\
            '--output[Write report to file]' \\
            '--exclude[Exclude paths matching glob]' \\
            '--include[Include only paths matching glob]' \\
            '--config[Load config from explicit file]' \\
            '--warnings[Stderr warning presentation: summary|full]' \\
            '*:path:_files'
          ;;
        compare)
          _arguments \\
            '--baseline[Baseline ScanResult JSON]' \\
            '--since[Git history window]' \\
            '--format[Output format]' \\
            '--output[Write report to file]' \\
            '--exclude[Exclude paths matching glob]' \\
            '--include[Include only paths matching glob]' \\
            '--config[Load config from explicit file]' \\
            '--warnings[Stderr warning presentation: summary|full]' \\
            '*:path:_files'
          ;;
        baseline)
          if (( CURRENT == 2 )); then
            _describe 'subcommand' '(save)'
          else
            _arguments \\
              '--output[Baseline file path]' \\
              '--since[Git history window]' \\
              '--exclude[Exclude paths matching glob]' \\
              '--include[Include only paths matching glob]' \\
              '--config[Load config from explicit file]' \\
              '--warnings[Stderr warning presentation: summary|full]' \\
              '*:path:_files'
          fi
          ;;
        completion)
          _arguments '1:shell:(bash zsh fish)'
          ;;
        *)
          _arguments '*:::( )'
          ;;
      esac
      ;;
  esac
}

_hotspot_scanner
`;

