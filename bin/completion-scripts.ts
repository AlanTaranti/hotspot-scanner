function flagWordList(defs: readonly FlagDef[]): string {
  return defs.map((flag) => `--${flag.long}`).join(" ");
}

const SCAN_FLAGS = flagWordList(SCAN_FLAG_DEFS);
const ASSESS_FLAGS = flagWordList(ASSESS_FLAG_DEFS);
const TREND_FLAGS = flagWordList(TREND_FLAG_DEFS);

function zshFlagArguments(defs: readonly FlagDef[]): string {
  return defs
    .map((flag) => `'--${flag.long}[${flag.desc}]' \\`)
    .join("\n            ");
}

function fishFlagCompletes(
  subcommand: string,
  condition: string,
  defs: readonly FlagDef[],
): string {
  return defs
    .map(
      (flag) =>
        `complete -c hotspot-scanner -n '${condition}' -l ${flag.long} -d '${flag.desc}'`,
    )
    .join("\n");
}

const BASH_COMPLETION_SCRIPT = `# hotspot-scanner bash completion
# Generated by: hotspot-scanner completion bash

_hotspot_scanner() {
  local cur
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"

  if [[ \${COMP_CWORD} -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "${TOP_LEVEL_COMMANDS}" -- "\${cur}") )
    return 0
  fi

  case "\${COMP_WORDS[1]}" in
    scan)
      COMPREPLY=( $(compgen -W "${SCAN_FLAGS} --help" -- "\${cur}") )
      ;;
    assess)
      COMPREPLY=( $(compgen -W "${ASSESS_FLAGS} --help" -- "\${cur}") )
      ;;
    trend)
      COMPREPLY=( $(compgen -W "${TREND_FLAGS} --help" -- "\${cur}") )
      ;;
    completion)
      COMPREPLY=( $(compgen -W "bash zsh fish" -- "\${cur}") )
      ;;
    *)
      COMPREPLY=( $(compgen -W "--help" -- "\${cur}") )
      ;;
  esac
}

complete -F _hotspot_scanner hotspot-scanner
`;

const ZSH_COMPLETION_SCRIPT = `#compdef hotspot-scanner

_hotspot_scanner() {
  local context state line
  typeset -A opt_args

  _arguments -C \\
    '1: :->command' \\
    '*:: :->args'

  case $state in
    command)
      local -a commands
      commands=(
        'init:Write exemplar .hotspot-scanner.json'
        'doctor:Check Node, git, repository, and config readiness'
        'trend:Show complexity trend for one file'
        'assess:Run hotspot assess on top candidates'
        'scan:Run hotspot analysis'
        'completion:Print shell completion script'
      )
      _describe 'command' commands
      ;;
    args)
      case $words[1] in
        scan)
          _arguments \\
            ${zshFlagArguments(SCAN_FLAG_DEFS)}
            '*:path:_files'
          ;;
        assess)
          _arguments \\
            ${zshFlagArguments(ASSESS_FLAG_DEFS)}
            '*:path:_files'
          ;;
        trend)
          _arguments \\
            ${zshFlagArguments(TREND_FLAG_DEFS)}
            '*:file:_files'
          ;;
        completion)
          _arguments '1:shell:(bash zsh fish)'
          ;;
        *)
          _arguments '*:::( )'
          ;;
      esac
      ;;
  esac
}

_hotspot_scanner
`;

