function isCompletionShell(shell: string): shell is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(shell);
}

export function getCompletionScript(shell: string): string {
  if (!isCompletionShell(shell)) {
    throw new CliUsageError(
      `Invalid shell: ${shell}. Expected one of: ${COMPLETION_SHELLS.join(", ")}.`,
    );
  }

  switch (shell) {
    case "bash":
      return BASH_COMPLETION_SCRIPT;
    case "zsh":
      return ZSH_COMPLETION_SCRIPT;
    case "fish":
      return FISH_COMPLETION_SCRIPT;
  }
}
